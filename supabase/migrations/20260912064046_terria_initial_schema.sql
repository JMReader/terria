create policy "profiles are visible to their owner" on core.profiles
for select to authenticated using ((select auth.uid()) = id);
create policy "profiles are updated by their owner" on core.profiles
for update to authenticated using ((select auth.uid()) = id) with check ((select auth.uid()) = id);

create policy "owners manage their fields" on core.fields
for all to authenticated
using ((select auth.uid()) = owner_id)
with check ((select auth.uid()) = owner_id);

create policy "owners read field documents" on core.documents
for select to authenticated using (
  exists (select 1 from core.fields f where f.id = field_id and f.owner_id = (select auth.uid()))
);
create policy "owners read field audit" on core.audit_log
for select to authenticated using (
  exists (select 1 from core.fields f where f.id = field_id and f.owner_id = (select auth.uid()))
);
create policy "authenticated users read source catalog" on satellite.sources
for select to authenticated using (true);

